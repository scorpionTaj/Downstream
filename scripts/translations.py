def esc(s): return s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
for index, lang in ((0, 'fr'), (1, 'ar')):
    folder = out / f'{lang}.lproj'
    folder.mkdir(parents=True, exist_ok=True)
    lines = [f'/* Downstream – {lang}. Generated from scripts; keys are the English text. */']
    for key in sorted(T):
        value = T[key][index]
        assert key.count('%@') == value.count('%@') and key.count('%lld') == value.count('%lld'), (lang, key)
        lines.append(f'"{esc(key)}" = "{esc(value)}";')
    (folder / 'Localizable.strings').write_text('\n'.join(lines) + '\n', encoding='utf-8')
